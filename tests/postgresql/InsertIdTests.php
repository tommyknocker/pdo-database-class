<?php

declare(strict_types=1);

namespace tommyknocker\pdodb\tests\postgresql;

/**
 * insert() returns the id of the row that was inserted: lastval() alone would return the last sequence value of
 * the session, whichever table it came from.
 */
final class InsertIdTests extends BasePostgreSQLTestCase
{
    protected function tearDown(): void
    {
        foreach (['insert_id_serial', 'insert_id_text', 'insert_id_identity', 'insert_id_default', 'insert_id_later'] as $table) {
            self::$db->schema()->dropTableIfExists($table);
        }
        self::$db->rawQuery('DROP SEQUENCE IF EXISTS insert_id_default_seq');
        parent::tearDown();
    }

    private function createTables(): void
    {
        $schema = self::$db->schema();
        $schema->dropTableIfExists('insert_id_serial');
        $schema->dropTableIfExists('insert_id_text');
        $schema->createTable('insert_id_serial', ['id' => $schema->primaryKey(), 'amount' => $schema->integer()->notNull()]);
        $schema->createTable('insert_id_text', ['id' => $schema->string(36)->notNull()->unique(), 'amount' => $schema->integer()->notNull()]);
    }

    public function testGeneratedIdsAreReturned(): void
    {
        $this->createTables();

        $this->assertSame(1, self::$db->find()->table('insert_id_serial')->insert(['amount' => 1]));
        $this->assertSame(2, self::$db->find()->table('insert_id_serial')->insert(['amount' => 2]));
        $this->assertSame(3, self::$db->transaction(fn () => self::$db->find()->table('insert_id_serial')->insert(['amount' => 3])));
    }

    public function testASuppliedKeyIsReturned(): void
    {
        $this->createTables();
        self::$db->find()->table('insert_id_serial')->insert(['amount' => 1]);

        $this->assertSame(77, self::$db->find()->table('insert_id_serial')->insert(['id' => 77, 'amount' => 2]));
    }

    public function testATableWithoutAGeneratedKeyDoesNotReturnAnotherTablesId(): void
    {
        $this->createTables();
        foreach ([1, 2, 3] as $amount) {
            self::$db->find()->table('insert_id_serial')->insert(['amount' => $amount]); // the session's lastval() is now 3
        }

        $result = self::$db->find()->table('insert_id_text')->insert(['id' => 'abc', 'amount' => 1]);

        $this->assertNull($result, 'no generated key: null, not the id of an insert into another table');
    }

    public function testAnUpsertStillReturnsTheId(): void
    {
        $this->createTables();

        $first = self::$db->find()->table('insert_id_serial')->insert(['id' => 5, 'amount' => 1], ['amount']);
        $again = self::$db->find()->table('insert_id_serial')->insert(['id' => 5, 'amount' => 2], ['amount']);

        $this->assertSame([5, 5], [$first, $again]);
    }

    public function testIdentityColumnsReturnTheirIds(): void
    {
        self::$db->schema()->dropTableIfExists('insert_id_identity');
        self::$db->rawQuery('CREATE TABLE insert_id_identity (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount INT)');

        $ids = [
            self::$db->find()->table('insert_id_identity')->insert(['amount' => 1]),
            self::$db->find()->table('insert_id_identity')->insert(['amount' => 2]),
            self::$db->find()->table('insert_id_identity')->insert(['id' => 9, 'amount' => 3]),
        ];

        $this->assertSame([1, 2, 9], $ids);
    }

    public function testAHandMadeNextvalDefaultReturnsItsId(): void
    {
        self::$db->schema()->dropTableIfExists('insert_id_default');
        self::$db->rawQuery('DROP SEQUENCE IF EXISTS insert_id_default_seq');
        self::$db->rawQuery('CREATE SEQUENCE insert_id_default_seq');
        self::$db->rawQuery("CREATE TABLE insert_id_default (id INT PRIMARY KEY DEFAULT nextval('insert_id_default_seq'), amount INT)");

        $ids = [
            self::$db->find()->table('insert_id_default')->insert(['amount' => 1]),
            self::$db->find()->table('insert_id_default')->insert(['amount' => 2]),
            self::$db->find()->table('insert_id_default')->insert(['id' => 40, 'amount' => 3]),
        ];

        $this->assertSame([1, 2, 40], $ids);
    }

    public function testAKeyAddedAfterTheFirstInsertIsPickedUp(): void
    {
        self::$db->schema()->dropTableIfExists('insert_id_later');
        self::$db->rawQuery('CREATE TABLE insert_id_later (amount INT)');
        self::$db->find()->table('insert_id_later')->insert(['amount' => 1]); // no generated key yet
        self::$db->rawQuery('ALTER TABLE insert_id_later ADD COLUMN id INT GENERATED BY DEFAULT AS IDENTITY');

        $ids = [
            self::$db->find()->table('insert_id_later')->insert(['amount' => 2]),
            self::$db->find()->table('insert_id_later')->insert(['amount' => 3]),
        ];

        $this->assertSame([2, 3], $ids);
    }

    public function testALookupInsideATransactionDoesNotAbortIt(): void
    {
        self::$db->schema()->dropTableIfExists('insert_id_text');
        self::$db->rawQuery('CREATE TABLE insert_id_text (id VARCHAR(36), amount INT)');

        self::$db->transaction(function (): void {
            self::$db->find()->table('insert_id_text')->insert(['id' => 'a', 'amount' => 1]);
            self::$db->find()->table('insert_id_text')->insert(['id' => 'b', 'amount' => 2]);
        });

        $this->assertSame(2, (int)self::$db->rawQueryValue('SELECT COUNT(*) FROM insert_id_text'));
    }
}
